CREATE TABLE rt.schema_migrations (
    version varchar(96) PRIMARY KEY,
    checksum_sha256 char(64) NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (checksum_sha256 ~ '^[0-9a-f]{64}$')
);

CREATE FUNCTION rt.reject_immutable_change() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'pg_catalog', 'rt', 'ref'
    AS $$
BEGIN
    RAISE EXCEPTION '% is immutable', TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME;
END;
$$;

CREATE TABLE ref.securities (
    security_id uuid PRIMARY KEY,
    asset_type varchar(12) NOT NULL,
    source_origin varchar(64) NOT NULL,
    created_at timestamptz NOT NULL,
    CHECK (asset_type IN ('STOCK', 'ETF', 'INDEX')),
    CHECK (btrim(source_origin) <> '')
);

CREATE TABLE ref.security_revisions (
    revision_id uuid PRIMARY KEY,
    security_id uuid NOT NULL REFERENCES ref.securities(security_id),
    ticker varchar(32) NOT NULL,
    exchange varchar(32),
    calendar_id varchar(64) NOT NULL,
    effective_from timestamptz NOT NULL,
    effective_to timestamptz,
    observed_at timestamptz NOT NULL,
    payload_sha256 char(64) NOT NULL,
    imported_at timestamptz,
    UNIQUE (security_id, effective_from, payload_sha256),
    CHECK (ticker = upper(ticker) AND btrim(ticker) <> ''),
    CHECK (btrim(calendar_id) <> ''),
    CHECK (effective_to IS NULL OR effective_to > effective_from),
    CHECK (observed_at >= effective_from),
    CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (imported_at IS NULL OR imported_at >= observed_at)
);

CREATE UNIQUE INDEX uq_ref_security_current_revision
    ON ref.security_revisions (security_id)
    WHERE effective_to IS NULL;
CREATE INDEX idx_ref_security_revision_ticker
    ON ref.security_revisions (ticker, effective_from DESC);

CREATE TABLE ref.option_contracts (
    contract_id bigint PRIMARY KEY,
    underlying_security_id uuid NOT NULL REFERENCES ref.securities(security_id),
    provider varchar(32) NOT NULL,
    contract_ticker varchar(64) NOT NULL,
    first_observed_at timestamptz NOT NULL,
    source_origin varchar(64) NOT NULL,
    UNIQUE (provider, contract_ticker),
    CHECK (contract_id > 0),
    CHECK (contract_ticker = upper(contract_ticker)),
    CHECK (btrim(provider) <> '' AND btrim(source_origin) <> '')
);

CREATE INDEX idx_ref_option_contract_underlying
    ON ref.option_contracts (underlying_security_id, contract_id);

CREATE TABLE ref.option_contract_versions (
    version_id bigint PRIMARY KEY,
    contract_id bigint NOT NULL REFERENCES ref.option_contracts(contract_id),
    call_put char(1) NOT NULL,
    expiration date NOT NULL,
    strike numeric(20,8) NOT NULL,
    exercise_style varchar(16) NOT NULL,
    multiplier numeric(20,8) NOT NULL,
    deliverables jsonb NOT NULL DEFAULT '[]'::jsonb,
    eligibility varchar(32) NOT NULL,
    effective_from timestamptz NOT NULL,
    effective_to timestamptz,
    observed_at timestamptz NOT NULL,
    payload_sha256 char(64) NOT NULL,
    imported_at timestamptz,
    UNIQUE (contract_id, effective_from, payload_sha256),
    CHECK (version_id > 0),
    CHECK (call_put IN ('C', 'P')),
    CHECK (strike > 0 AND multiplier > 0),
    CHECK (exercise_style IN ('AMERICAN', 'EUROPEAN')),
    CHECK (jsonb_typeof(deliverables) = 'array'),
    CHECK (eligibility IN ('VALIDATED_ACTIVE', 'REJECTED_UNSUPPORTED', 'EXPIRED')),
    CHECK (effective_to IS NULL OR effective_to > effective_from),
    CHECK (observed_at >= effective_from),
    CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (imported_at IS NULL OR imported_at >= observed_at)
);

CREATE UNIQUE INDEX uq_ref_option_contract_current_version
    ON ref.option_contract_versions (contract_id)
    WHERE effective_to IS NULL;
CREATE INDEX idx_ref_option_contract_version_expiry
    ON ref.option_contract_versions (expiration, contract_id)
    WHERE effective_to IS NULL AND eligibility = 'VALIDATED_ACTIVE';

CREATE TABLE rt.instruments (
    instrument_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_class varchar(12) NOT NULL,
    security_id uuid REFERENCES ref.securities(security_id),
    contract_id bigint REFERENCES ref.option_contracts(contract_id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (asset_class IN ('EQUITY', 'OPTION')),
    CHECK (
        (asset_class = 'EQUITY' AND security_id IS NOT NULL AND contract_id IS NULL)
        OR
        (asset_class = 'OPTION' AND security_id IS NULL AND contract_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_rt_instrument_security
    ON rt.instruments (security_id)
    WHERE security_id IS NOT NULL;
CREATE UNIQUE INDEX uq_rt_instrument_contract
    ON rt.instruments (contract_id)
    WHERE contract_id IS NOT NULL;

CREATE TABLE rt.capability_profiles (
    profile_id uuid PRIMARY KEY,
    config_sha256 char(64) NOT NULL,
    schema_sha256 char(64) NOT NULL,
    account_alias varchar(64) NOT NULL,
    capabilities_sha256 char(64) NOT NULL,
    universe_sha256 char(64) NOT NULL,
    checked_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    status varchar(16) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (
        config_sha256,
        schema_sha256,
        account_alias,
        capabilities_sha256,
        universe_sha256,
        checked_at
    ),
    CHECK (config_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (schema_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (capabilities_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (universe_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (btrim(account_alias) <> ''),
    CHECK (expires_at > checked_at),
    CHECK (status IN ('PASS', 'FAIL', 'UNAVAILABLE', 'EXPIRED'))
);

CREATE INDEX idx_rt_capability_profile_lookup
    ON rt.capability_profiles (
        account_alias,
        universe_sha256,
        checked_at DESC
    );

CREATE TABLE rt.capability_checks (
    profile_id uuid NOT NULL REFERENCES rt.capability_profiles(profile_id),
    check_name varchar(64) NOT NULL,
    scope_key varchar(160) NOT NULL,
    verdict varchar(24) NOT NULL,
    required boolean NOT NULL,
    reason_codes text[] NOT NULL DEFAULT ARRAY[]::text[],
    observed_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (profile_id, check_name, scope_key),
    CHECK (btrim(check_name) <> '' AND btrim(scope_key) <> ''),
    CHECK (verdict IN ('PASS', 'FAIL', 'UNAVAILABLE', 'EXPIRED', 'NOT_APPLICABLE')),
    CHECK (expires_at > observed_at),
    CHECK (jsonb_typeof(evidence) = 'object'),
    CHECK ((verdict = 'PASS' AND cardinality(reason_codes) = 0) OR verdict <> 'PASS'),
    CHECK ((verdict <> 'PASS' AND cardinality(reason_codes) > 0) OR verdict = 'PASS'),
    CHECK (verdict <> 'NOT_APPLICABLE' OR required = false)
);

CREATE TABLE rt.subscription_manifests (
    manifest_id uuid PRIMARY KEY,
    manifest_sha256 char(64) NOT NULL UNIQUE,
    universe_sha256 char(64) NOT NULL,
    session_date date NOT NULL,
    effective_at timestamptz NOT NULL,
    profile_id uuid NOT NULL REFERENCES rt.capability_profiles(profile_id),
    stock_count integer NOT NULL,
    option_underlying_count integer NOT NULL,
    option_quote_contract_count integer NOT NULL,
    member_count integer NOT NULL,
    allocation_policy_sha256 char(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (manifest_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (universe_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (allocation_policy_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (stock_count > 0),
    CHECK (option_underlying_count BETWEEN 1 AND stock_count),
    CHECK (option_quote_contract_count BETWEEN option_underlying_count AND 1000),
    CHECK (member_count >= stock_count * 3 + option_quote_contract_count * 2)
);

CREATE INDEX idx_rt_subscription_manifest_session
    ON rt.subscription_manifests (session_date DESC, effective_at DESC);

CREATE TABLE rt.subscription_members (
    manifest_id uuid NOT NULL REFERENCES rt.subscription_manifests(manifest_id),
    instrument_id bigint NOT NULL REFERENCES rt.instruments(instrument_id),
    feed varchar(12) NOT NULL,
    channel varchar(4) NOT NULL,
    priority smallint NOT NULL,
    purpose varchar(24) NOT NULL,
    catalog_version_id bigint REFERENCES ref.option_contract_versions(version_id),
    PRIMARY KEY (manifest_id, feed, channel, instrument_id),
    CHECK (feed IN ('STOCKS', 'OPTIONS')),
    CHECK (channel IN ('T', 'Q', 'AM')),
    CHECK (priority BETWEEN 1 AND 32767),
    CHECK (purpose IN ('PRIMARY', 'RETAINED_ALERT', 'POSITION')),
    CHECK (feed <> 'OPTIONS' OR catalog_version_id IS NOT NULL),
    CHECK (feed <> 'OPTIONS' OR channel IN ('T', 'Q')),
    CHECK (feed <> 'STOCKS' OR channel IN ('T', 'Q', 'AM'))
);

CREATE INDEX idx_rt_subscription_member_instrument
    ON rt.subscription_members (instrument_id, manifest_id);

CREATE TABLE rt.cohorts (
    cohort_id uuid PRIMARY KEY,
    cohort_sha256 char(64) NOT NULL UNIQUE,
    manifest_id uuid NOT NULL REFERENCES rt.subscription_manifests(manifest_id),
    configuration_sha256 char(64) NOT NULL,
    model_bundle_sha256 char(64) NOT NULL,
    valuation_sha256 char(64) NOT NULL,
    effective_at timestamptz NOT NULL,
    mode varchar(16) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (cohort_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (configuration_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (model_bundle_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (valuation_sha256 ~ '^[0-9a-f]{64}$'),
    CHECK (mode IN ('SHADOW', 'ALERT', 'PAPER', 'LIVE'))
);

CREATE TABLE rt.worker_leases (
    resource_key varchar(192) PRIMARY KEY,
    owner_id uuid NOT NULL,
    owner_epoch bigint NOT NULL,
    lease_until timestamptz NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (btrim(resource_key) <> ''),
    CHECK (owner_epoch > 0)
) WITH (fillfactor = 80);

CREATE TABLE rt.readiness_current (
    scope_type varchar(24) NOT NULL,
    scope_id varchar(160) NOT NULL,
    capability varchar(64) NOT NULL,
    epoch bigint NOT NULL,
    owner_epoch bigint NOT NULL,
    profile_id uuid NOT NULL REFERENCES rt.capability_profiles(profile_id),
    status varchar(16) NOT NULL,
    reasons text[] NOT NULL DEFAULT ARRAY[]::text[],
    checked_at timestamptz NOT NULL,
    lease_until timestamptz NOT NULL,
    source_watermark jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (scope_type, scope_id, capability),
    CHECK (btrim(scope_type) <> '' AND btrim(scope_id) <> ''),
    CHECK (btrim(capability) <> ''),
    CHECK (epoch > 0 AND owner_epoch > 0),
    CHECK (status IN ('READY', 'DEGRADED', 'BLOCKED')),
    CHECK (lease_until > checked_at),
    CHECK (jsonb_typeof(source_watermark) = 'object'),
    CHECK ((status = 'READY' AND cardinality(reasons) = 0) OR status <> 'READY'),
    CHECK ((status <> 'READY' AND cardinality(reasons) > 0) OR status = 'READY')
) WITH (fillfactor = 80);

CREATE TABLE rt.readiness_transitions (
    transition_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    scope_type varchar(24) NOT NULL,
    scope_id varchar(160) NOT NULL,
    capability varchar(64) NOT NULL,
    epoch bigint NOT NULL,
    owner_epoch bigint NOT NULL,
    profile_id uuid NOT NULL REFERENCES rt.capability_profiles(profile_id),
    previous_status varchar(16),
    status varchar(16) NOT NULL,
    reasons text[] NOT NULL DEFAULT ARRAY[]::text[],
    transitioned_at timestamptz NOT NULL,
    lease_until timestamptz NOT NULL,
    source_watermark jsonb NOT NULL DEFAULT '{}'::jsonb,
    CHECK (epoch > 0 AND owner_epoch > 0),
    CHECK (previous_status IS NULL OR previous_status IN ('READY', 'DEGRADED', 'BLOCKED')),
    CHECK (status IN ('READY', 'DEGRADED', 'BLOCKED')),
    CHECK (lease_until > transitioned_at),
    CHECK (jsonb_typeof(source_watermark) = 'object')
);

CREATE INDEX idx_rt_readiness_transition_scope
    ON rt.readiness_transitions (
        scope_type,
        scope_id,
        capability,
        transitioned_at DESC
    );

CREATE TABLE rt.stream_sessions (
    session_id uuid PRIMARY KEY,
    provider varchar(32) NOT NULL,
    feed varchar(12) NOT NULL,
    manifest_id uuid NOT NULL REFERENCES rt.subscription_manifests(manifest_id),
    owner_id uuid NOT NULL,
    owner_epoch bigint NOT NULL,
    started_at timestamptz NOT NULL,
    authenticated_at timestamptz,
    subscribed_at timestamptz,
    ended_at timestamptz,
    status varchar(24) NOT NULL,
    failure_code varchar(64),
    CHECK (btrim(provider) <> ''),
    CHECK (feed IN ('STOCKS', 'OPTIONS')),
    CHECK (owner_epoch > 0),
    CHECK (status IN (
        'CONNECTING', 'AUTHENTICATING', 'SUBSCRIBING', 'WARMING',
        'LIVE', 'BACKOFF', 'BLOCKED', 'STOPPING', 'STOPPED', 'FAILED'
    )),
    CHECK (authenticated_at IS NULL OR authenticated_at >= started_at),
    CHECK (subscribed_at IS NULL OR subscribed_at >= started_at),
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE UNIQUE INDEX uq_rt_active_stream_owner
    ON rt.stream_sessions (provider, feed)
    WHERE ended_at IS NULL
      AND status NOT IN ('STOPPED', 'FAILED');
CREATE INDEX idx_rt_stream_session_manifest
    ON rt.stream_sessions (manifest_id, started_at DESC);

CREATE TABLE rt.stream_gaps (
    gap_id uuid PRIMARY KEY,
    session_id uuid NOT NULL REFERENCES rt.stream_sessions(session_id),
    instrument_id bigint REFERENCES rt.instruments(instrument_id),
    channel varchar(4),
    gap_start timestamptz NOT NULL,
    gap_end timestamptz,
    journal_generation uuid NOT NULL,
    shard_id smallint NOT NULL,
    last_durable_offset bigint NOT NULL,
    reason varchar(64) NOT NULL,
    recovery_status varchar(24) NOT NULL,
    repair_reference uuid,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (channel IS NULL OR channel IN ('T', 'Q', 'AM')),
    CHECK (gap_end IS NULL OR gap_end >= gap_start),
    CHECK (shard_id >= 0),
    CHECK (last_durable_offset >= 0),
    CHECK (btrim(reason) <> ''),
    CHECK (recovery_status IN ('UNRESOLVED', 'WARMING', 'AGED_OUT', 'REPAIRED', 'WAIVED'))
);

CREATE INDEX idx_rt_unresolved_stream_gap
    ON rt.stream_gaps (session_id, gap_start, gap_id)
    WHERE recovery_status IN ('UNRESOLVED', 'WARMING');
CREATE INDEX idx_rt_stream_gap_instrument
    ON rt.stream_gaps (instrument_id, gap_start DESC)
    WHERE instrument_id IS NOT NULL;

